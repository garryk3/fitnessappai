/// Интерфейс синхронизации данных.
///
/// Базовый контракт для локального переноса данных через файл БД
/// ([LocalFileSyncService]) и будущей облачной синхронизации.
abstract class SyncService {
  /// Создаёт резервную копию текущей БД и возвращает путь к файлу.
  Future<String> export();

  /// Импортирует БД из [sourcePath]: валидирует файл, заменяет им
  /// текущую БД и перезапускает приложение.
  Future<void> import(String sourcePath);
}
