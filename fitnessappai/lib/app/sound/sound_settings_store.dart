/// Хранилище настроек звука: переключатель и путь к файлу.
///
/// Общий интерфейс для сигналов таймеров ([SoundSettingsRepository]) и
/// напоминаний о тренировках ([ReminderSoundSettingsRepository]) — оба
/// используют один и тот же контроллер и плеер (задача 47.5).
///
/// Абстрактный класс, а не `implements`-интерфейс: последние два метода имеют
/// умолчания, пригодные обоим хранилищам, и наследование избавляет от
/// дублирования в заглушках тестов.
abstract class SoundSettingsStore {
  /// Включён ли звук (по умолчанию — включён).
  Future<bool> isEnabled();

  /// Путь к выбранному пользователем файлу (null — встроенный сигнал).
  Future<String?> soundFilePath();

  /// Сохраняет переключатель звука.
  Future<void> setEnabled(bool enabled);

  /// Сохраняет путь к выбранному файлу (null — встроенный сигнал).
  Future<void> setSoundFile(String? path);

  /// Может ли **системный процесс** прочитать сохранённый файл.
  ///
  /// Нужно для звука канала уведомлений: его играет `system_server`, а файл из
  /// приватного хранилища приложения ему недоступен — Android тогда
  /// откатывается на стандартный сигнал (задача 48.1). По умолчанию `true`:
  /// предпрослушивание файл из приватного каталога читает сам, ограничение
  /// касается только системного воспроизведения.
  Future<bool> isSoundSystemReadable() async => true;

  /// Приводит сохранённый файл в порядок при загрузке настроек.
  ///
  /// Вызывается сервисом перед применением звука: у напоминаний это шанс
  /// перенести ранее выбранный файл в доступное системе хранилище, чтобы
  /// владельцу не пришлось выбирать его заново (48.1). По умолчанию ничего не
  /// делает.
  Future<void> ensureSoundFileReady() async {}
}

/// Снимок настроек звука — то, что контроллер сообщает наружу после
/// изменения, чтобы применить настройки там, где это нужно (например,
/// пересоздать канал уведомлений).
class SoundSettingsSnapshot {
  const SoundSettingsSnapshot({
    required this.enabled,
    required this.filePath,
    this.systemReadable = true,
  });

  /// Включён ли звук.
  final bool enabled;

  /// Путь к выбранному файлу (null — встроенный сигнал).
  final String? filePath;

  /// Читаем ли [filePath] системным процессом — см.
  /// [SoundSettingsStore.isSoundSystemReadable].
  final bool systemReadable;
}
